"""Build byte-for-byte verified, lossless offline pages and a static upload ZIP.

Run from any directory. Outputs stay in build/; generated Dart metadata is small.
No source SVG, ayah polygon, or Quran text is rewritten.
"""

import concurrent.futures
import gzip
import hashlib
import json
from pathlib import Path
import re
import shutil
import time
import urllib.request
import zipfile

ROOT = Path(__file__).resolve().parents[1]
REVISION = "3ff27b46cecb0c0519d77531d9c868a579d1f623"
BASE = f"https://raw.githubusercontent.com/quran-ws/quran-svg/{REVISION}/mushafs/hafs/kfqc"
RELEASE = ROOT / "build/mushaf-compressed-release"
PUBLIC = RELEASE / "public/quran-pages" / REVISION
CACHE = ROOT / "build/mushaf-source-cache"


def git_blob(data):
    return hashlib.sha1(f"blob {len(data)}\0".encode() + data).hexdigest()


def asset(page, kind, length, expected):
    source = CACHE / kind / f"{page:03}.{kind}"
    source.parent.mkdir(parents=True, exist_ok=True)
    raw = source.read_bytes() if source.exists() else b""
    if len(raw) != length or git_blob(raw) != expected:
        for attempt in range(4):
            try:
                request = urllib.request.Request(
                    f"{BASE}/{kind}/{page:03}.{kind}",
                    headers={"Accept-Encoding": "identity", "User-Agent": "Haq-Mushaf-Packager"},
                )
                with urllib.request.urlopen(request, timeout=60) as response:
                    raw = response.read(length + 1)
                if len(raw) != length or git_blob(raw) != expected:
                    raise ValueError(f"Source checksum mismatch: {page}/{kind}")
                source.write_bytes(raw)
                break
            except Exception:
                if attempt == 3:
                    raise
                time.sleep(2 ** attempt)
    packed = gzip.compress(raw, compresslevel=9, mtime=0)
    assert gzip.decompress(packed) == raw
    target = PUBLIC / kind / f"{page:03}.{kind}.qgz"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(packed)
    return len(packed), hashlib.sha256(packed).hexdigest()


def page_assets(row):
    page, svg_length, svg_blob, json_length, json_blob = row
    svg = asset(int(page), "svg", int(svg_length), svg_blob)
    metadata = asset(int(page), "json", int(json_length), json_blob)
    return int(page), svg, metadata


def main():
    source = (ROOT / "lib/features/quran/data/quran_page_downloads.dart").read_text(encoding="utf-8")
    rows = re.findall(r"^(\d+) (\d+) ([a-f0-9]{40}) (\d+) ([a-f0-9]{40})$", source, re.M)
    if len(rows) != 604 or {int(row[0]) for row in rows} != set(range(1, 605)):
        raise ValueError("Expected the pinned 604-page manifest")
    completed = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
        jobs = [pool.submit(page_assets, row) for row in rows]
        for job in concurrent.futures.as_completed(jobs):
            completed.append(job.result())
            if len(completed) % 40 == 0 or len(completed) == 604:
                print(f"Verified and compressed {len(completed)}/604 pages", flush=True)
    completed.sort()
    original = sum(int(row[1]) + int(row[3]) for row in rows)
    compressed = sum(svg[0] + metadata[0] for _, svg, metadata in completed)
    report = {
        "sourceRevision": REVISION,
        "pages": 604,
        "originalBytes": original,
        "compressedBytes": compressed,
        "originalMiB": round(original / 1024**2, 2),
        "compressedMiB": round(compressed / 1024**2, 2),
        "savingPercent": round((1 - compressed / original) * 100, 2),
        "assets": [
            {"page": page, "svgBytes": svg[0], "svgSha256": svg[1],
             "jsonBytes": metadata[0], "jsonSha256": metadata[1]}
            for page, svg, metadata in completed
        ],
    }
    (PUBLIC / "manifest.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    for source_name, target_name in [("offline-page-LICENSE.txt", "LICENSE.txt"), ("offline-page-NOTICE.md", "NOTICE.md")]:
        shutil.copyfile(ROOT / "assets/quran" / source_name, PUBLIC / target_name)
    (PUBLIC / ".htaccess").write_text(
        '<IfModule mod_mime.c>\n  AddType application/octet-stream .qgz\n'
        '  RemoveEncoding .qgz\n</IfModule>\n'
        '<IfModule mod_headers.c>\n  <FilesMatch "\\.qgz$">\n'
        '    Header unset Content-Encoding\n'
        '    Header set Cache-Control "public, max-age=31536000, immutable"\n'
        '  </FilesMatch>\n</IfModule>\n', encoding="utf-8",
    )
    manifest = ROOT / "lib/features/quran/data/quran_page_compressed_manifest.dart"
    lines = [f"{page} {svg[0]} {svg[1]} {metadata[0]} {metadata[1]}" for page, svg, metadata in completed]
    manifest.write_text(
        "// Generated by tool/build_compressed_mushaf.py. Do not edit.\n"
        f"// Source revision: {REVISION}; lossless gzip level 9.\n"
        "const quranCompressedPageManifest = '''\n" + "\n".join(lines) + "\n''';\n", encoding="utf-8",
    )
    (RELEASE / "size-report.json").write_text(json.dumps({k: v for k, v in report.items() if k != "assets"}, indent=2) + "\n", encoding="utf-8")
    archive = RELEASE / "mushaf-compressed-public.zip"
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_STORED) as bundle:
        for path in sorted((RELEASE / "public").rglob("*")):
            if path.is_file():
                bundle.write(path, path.relative_to(RELEASE))
    print(json.dumps({k: v for k, v in report.items() if k != "assets"}, indent=2), flush=True)
    print(f"Upload bundle: {archive}", flush=True)


if __name__ == "__main__":
    main()
