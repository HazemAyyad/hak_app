"""Generate immutable audio metadata, not audio downloads.

The archive filenames retain the publisher's bilingual identification. Audio
rights remain with their respective owners and require review before release.
"""
import hashlib
import json
from pathlib import Path
import re
import urllib.parse
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
REVISION = 'b9180a2bb769f74cff8e378ef2cc7aaf8db5cd5b'
SOURCE = 'https://github.com/Kiwifu/adhan-mp3'
cache = ROOT / 'build/adhan-public-tree.json'
if cache.exists():
    tree = json.loads(cache.read_text(encoding='utf-8'))
else:
    with urllib.request.urlopen(f'https://api.github.com/repos/Kiwifu/adhan-mp3/git/trees/{REVISION}?recursive=1', timeout=40) as response:
        tree = json.load(response)
assert tree['sha'] == REVISION and not tree['truncated']
files = [row for row in tree['tree'] if row['path'].endswith('.mp3')]
assert len(files) >= 200
seen = {}
rows = []
for file in files:
    path = file['path']
    match = re.search(r'\(([^()]*)\)\.mp3$', path)
    if not match:
        # Keep only recordings whose Arabic identity is supplied directly by
        # the archive. Do not invent names for the three unlabeled files.
        continue
    name = match.group(1).replace('_', ' ')
    count = seen[name] = seen.get(name, 0) + 1
    number = re.search(r'_(\d+)(?:_|\()', path)
    if number:
        name += f' • تسجيل {number.group(1)}'
    elif count > 1:
        name += f' • تسجيل {count}'
    if '_Fajr' in path and 'فجر' not in name:
        name += ' • الفجر'
    if '_HQ' in path:
        name += ' • جودة عالية'
    uid = 'archive-' + hashlib.sha256(path.encode()).hexdigest()[:16]
    url = f'https://raw.githubusercontent.com/Kiwifu/adhan-mp3/{REVISION}/' + urllib.parse.quote(path, safe='')
    rows.append((uid, name, url, file['sha'], file.get('size')))
lines = ["// Generated by tool/build_adhan_catalog.py; metadata only.", "part of 'prayer_alert.dart';", '', 'const _additionalAdhanVoices = [']
for uid, name, url, _, _ in rows:
    lines.append('  AdhanVoice(' + ', '.join(json.dumps(v, ensure_ascii=False) for v in [uid, name, url]) + ", source: 'مجموعة تسجيلات الأذان', sourceUrl: '" + SOURCE + "'),")
lines.append('];\n')
(ROOT / 'lib/features/prayer/data/adhan_catalog.dart').write_text('\n'.join(lines), encoding='utf-8')
manifest = {'source': SOURCE, 'revision': REVISION, 'recordings': len(rows), 'note': 'Publisher-provided metadata; attribution is not a recording-rights clearance.', 'files': [{'id': uid, 'name': name, 'url': url, 'gitBlobSha': sha, 'bytes': size} for uid, name, url, sha, size in rows]}
(ROOT / 'docs/adhan-audio-catalog.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
print(f'Generated {len(rows)} additional recording entries')
